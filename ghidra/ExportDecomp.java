// Post-analysis script: writes <out>/<program>.c (every function decompiled, in address order)
// and <out>/<program>.functions.tsv (address, name, size, mnemonic-sequence hash, callees).
// Usage: -postScript ExportDecomp.java <out_dir>
//@category G502

import java.io.File;
import java.io.PrintWriter;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeSet;

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileOptions;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.listing.InstructionIterator;
import ghidra.program.model.symbol.SourceType;

public class ExportDecomp extends GhidraScript {

	/** Rename functions from "address name" lines (# comments allowed). */
	private void applySymbols(File f) throws Exception {
		if (!f.exists()) {
			return;
		}
		for (String line : java.nio.file.Files.readAllLines(f.toPath())) {
			String[] p = line.replaceAll("#.*", "").trim().split("\\s+");
			if (p.length != 2) {
				continue;
			}
			Function fn = getFunctionAt(toAddr(Long.parseLong(p[0], 16)));
			if (fn == null) {
				printerr("no function at " + p[0] + " for " + p[1]);
				continue;
			}
			fn.setName(p[1], SourceType.USER_DEFINED);
		}
	}

	@Override
	public void run() throws Exception {
		String[] args = getScriptArgs();
		File out = new File(args.length > 0 ? args[0] : ".");
		out.mkdirs();
		String base = currentProgram.getName().replaceAll("\\.bin$", "");
		applySymbols(new File(getSourceFile().getParentFile().getFile(false),
			"symbols/" + base + ".txt"));

		DecompInterface di = new DecompInterface();
		DecompileOptions opts = new DecompileOptions();
		di.setOptions(opts);
		di.toggleCCode(true);
		di.openProgram(currentProgram);

		List<Function> funcs = new ArrayList<>();
		currentProgram.getFunctionManager().getFunctions(true).forEach(funcs::add);

		try (PrintWriter c = new PrintWriter(new File(out, base + ".c"));
				PrintWriter t = new PrintWriter(new File(out, base + ".functions.tsv"))) {
			c.println("// Ghidra decompilation of " + currentProgram.getName());
			c.println("// Generated by ghidra/ExportDecomp.java -- do not edit by hand.\n");
			t.println("address\tname\tsize\tninsn\tmnem_sha1\tcallees");
			for (Function f : funcs) {
				if (monitor.isCancelled()) {
					break;
				}
				StringBuilder mn = new StringBuilder();
				int ninsn = 0;
				InstructionIterator it = currentProgram.getListing().getInstructions(f.getBody(), true);
				while (it.hasNext()) {
					Instruction ins = it.next();
					mn.append(ins.getMnemonicString()).append(';');
					ninsn++;
				}
				MessageDigest md = MessageDigest.getInstance("SHA-1");
				StringBuilder hx = new StringBuilder();
				for (byte b : md.digest(mn.toString().getBytes())) {
					hx.append(String.format("%02x", b));
				}
				TreeSet<String> callees = new TreeSet<>();
				for (Function g : f.getCalledFunctions(monitor)) {
					callees.add(g.getEntryPoint().toString());
				}
				t.printf("%s\t%s\t%d\t%d\t%s\t%s%n", f.getEntryPoint(), f.getName(),
					f.getBody().getNumAddresses(), ninsn, hx, String.join(",", callees));

				DecompileResults r = di.decompileFunction(f, 120, monitor);
				c.printf("// ---- %s @ %s (%d bytes)%n", f.getName(), f.getEntryPoint(),
					f.getBody().getNumAddresses());
				if (r != null && r.decompileCompleted()) {
					c.println(r.getDecompiledFunction().getC());
				}
				else {
					c.println("// decompilation failed: " + (r != null ? r.getErrorMessage() : "?"));
				}
			}
		}
		di.dispose();
		println("exported " + funcs.size() + " functions to " + out);
	}
}
